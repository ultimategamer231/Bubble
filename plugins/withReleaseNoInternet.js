/**
 * Config plugin: strips android.permission.INTERNET from RELEASE builds only.
 *
 * It writes android/app/src/release/AndroidManifest.xml, a manifest overlay that
 * Gradle merges into release variants. `tools:node="remove"` deletes the permission
 * even when a library manifest declares it. Debug builds are untouched, so Metro
 * (the JS dev server) keeps working.
 *
 * Proof lives in the release permission dump (docs/PROGRESS.md, Phase 7).
 */
const { withDangerousMod } = require('expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

const RELEASE_MANIFEST = `<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools">
    <!-- Generated by plugins/withReleaseNoInternet.js. Focus Bubble ships without network access. -->
    <uses-permission android:name="android.permission.INTERNET" tools:node="remove" />
</manifest>
`;

function withReleaseNoInternet(config) {
  return withDangerousMod(config, [
    'android',
    (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'release');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'AndroidManifest.xml'), RELEASE_MANIFEST);
      return cfg;
    },
  ]);
}

module.exports = withReleaseNoInternet;
module.exports.RELEASE_MANIFEST = RELEASE_MANIFEST;
